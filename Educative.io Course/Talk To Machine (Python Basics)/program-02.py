#Python Arithmetic Operators: Add, Subtract, Multiply, Divide


print(4+7) #addition

print(10-5) #subtraction

print(10*5) #multiplication

print(10/2) #float division

print(10//2)  #floor division

print(10%2) #modulus

print(2 + 3 * 5) #17, not 25 (BODMAS rule)

print((2+3) * 5) #25 (BODMAS rule)